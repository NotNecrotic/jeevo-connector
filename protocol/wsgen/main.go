// Command wsgen turns x-jeevo-ws-messages in openapi.yaml into Go constants in internal/protocol/ws.gen.go.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"

	"gopkg.in/yaml.v3"
)

type message struct {
	Direction string `yaml:"direction"`
	Payload   string `yaml:"payload"`
	Reply     string `yaml:"reply"`
	Outbox    bool   `yaml:"outbox"`
}

func constName(t string) string {
	var b strings.Builder
	b.WriteString("Msg")
	for _, p := range strings.FieldsFunc(t, func(r rune) bool { return r == '.' || r == '-' || r == '_' }) {
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func main() {
	specPath := flag.String("spec", "", "openapi.yaml")
	out := flag.String("out", "", "output file")
	flag.Parse()
	raw, err := os.ReadFile(*specPath)
	if err != nil {
		log.Fatal(err)
	}
	// Decode into yaml.Node first so message order follows the file.
	var root yaml.Node
	if err := yaml.Unmarshal(raw, &root); err != nil {
		log.Fatal(err)
	}
	var version int
	var names []string
	msgs := map[string]message{}
	doc := root.Content[0]
	for i := 0; i < len(doc.Content); i += 2 {
		k, v := doc.Content[i].Value, doc.Content[i+1]
		switch k {
		case "info":
			for j := 0; j < len(v.Content); j += 2 {
				if v.Content[j].Value == "x-jeevo-protocol-version" {
					if _, err := fmt.Sscan(v.Content[j+1].Value, &version); err != nil {
						log.Fatalf("info.x-jeevo-protocol-version: %v", err)
					}
				}
			}
		case "x-jeevo-ws-messages":
			for j := 0; j < len(v.Content); j += 2 {
				var m message
				if err := v.Content[j+1].Decode(&m); err != nil {
					log.Fatal(err)
				}
				if m.Direction != "c2s" && m.Direction != "s2c" {
					log.Fatalf("%s: bad direction %q", v.Content[j].Value, m.Direction)
				}
				names = append(names, v.Content[j].Value)
				msgs[v.Content[j].Value] = m
			}
		}
	}
	if version < 1 {
		log.Fatal("info.x-jeevo-protocol-version missing")
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by protocol/wsgen from protocol/openapi.yaml. DO NOT EDIT.\n\npackage protocol\n\n")
	fmt.Fprintf(&b, "// ProtocolVersion is the control-channel protocol this build speaks.\nconst ProtocolVersion = %d\n\n", version)
	b.WriteString("// WebSocket message types.\nconst (\n\tMsgReply = \"reply\"\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%s = %q\n", constName(n), n)
	}
	b.WriteString(")\n\n// MessageInfo describes one message type.\ntype MessageInfo struct {\n\tDirection string // \"c2s\" or \"s2c\"\n\tOutbox bool // persisted and resent until acknowledged\n\tPayload string // schema name\n\tReply string // schema name of the reply payload, \"\" when none\n}\n\n// Messages maps every message type to its description.\nvar Messages = map[string]MessageInfo{\n")
	for _, n := range names {
		m := msgs[n]
		fmt.Fprintf(&b, "\t%s: {Direction: %q, Outbox: %v, Payload: %q, Reply: %q},\n", constName(n), m.Direction, m.Outbox, m.Payload, m.Reply)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
